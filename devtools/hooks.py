"""The `make dev-setup` hook step: the commit hook through pre-commit, the push gate as a shim.

Both hooks land in the shared hooks directory (`git rev-parse --git-common-dir`), so every
worktree of a clone runs them. Run `python -m devtools.hooks install` from the main checkout.
Every check runs before anything is written, and a hook the installer does not own is refused.
"""

import argparse
import os
import shutil
import stat
import subprocess
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

PRE_COMMIT_HEADER = "# File generated by pre-commit"
MARKER = "# tools-installer: pre-push gate (installed by make dev-setup; do not edit)"
_NO_UV = "pre-push: uv not found on PATH; install uv (see README) or push from a shell that has it"
SHIM = f"""#!/bin/sh
{MARKER}
if ! command -v uv >/dev/null 2>&1; then
    echo "{_NO_UV}" >&2
    exit 1
fi
exec uv run python -m devtools.push_gate "$@"
"""

Runner = Callable[[Sequence[str]], "subprocess.CompletedProcess[str]"]


def run_command(argv: Sequence[str]) -> "subprocess.CompletedProcess[str]":
    # LC_ALL=C keeps git's messages untranslated, so one text check works in every locale.
    return subprocess.run(
        list(argv),
        capture_output=True,
        text=True,
        check=False,
        env={**os.environ, "LC_ALL": "C"},
    )


def _fail(message: str) -> int:
    print(f"dev-setup: {message}", file=sys.stderr)
    return 1


def _lstat(path: Path) -> os.stat_result | None:
    try:
        return path.lstat()
    except FileNotFoundError:
        return None


def _entry_problem(path: Path, info: os.stat_result) -> str | None:
    """Why the installer must not write or hand `path` to pre-commit, or None when it may."""
    if not stat.S_ISREG(info.st_mode):
        return f"{path} is not a regular file; move or delete it, then re-run make dev-setup"
    if info.st_nlink > 1:
        return (
            f"{path} is hard-linked to another file; replace it with a plain copy or delete it, "
            "then re-run make dev-setup"
        )
    return None


def _text(path: Path) -> str:
    return path.read_bytes().decode("utf-8", errors="replace")


def _hook_problem(hooks: Path) -> str | None:
    """The first reason to refuse before anything is written, or None when both hooks are safe."""
    pre_push = hooks / "pre-push"
    info = _lstat(pre_push)
    if info is not None:
        problem = _entry_problem(pre_push, info)
        if problem is not None:
            return problem
        if MARKER not in _text(pre_push).splitlines():
            return f"{pre_push} is not ours; move or delete it, then re-run make dev-setup"
    pre_commit = hooks / "pre-commit"
    info = _lstat(pre_commit)
    if info is None:
        return None
    problem = _entry_problem(pre_commit, info)
    if problem is not None:
        return problem
    legacy = hooks / "pre-commit.legacy"
    # pre-commit's migration renames a foreign hook over an existing legacy file (shutil.move).
    if PRE_COMMIT_HEADER not in _text(pre_commit) and os.path.lexists(legacy):
        return (
            f"{pre_commit} is not pre-commit's and {legacy} exists, so pre-commit would replace "
            f"pre-commit.legacy with it; move one out of {hooks}, "
            "merging them first if both are needed"
        )
    return None


def install(
    *,
    run: Runner | None = None,
    which: Callable[[str], str | None] = shutil.which,
) -> int:
    run = run or run_command
    git = which("git")
    if git is None:
        print("dev-setup: git not found on PATH; skipping the git hook install")
        return 0
    common = run([git, "rev-parse", "--path-format=absolute", "--git-common-dir"])
    if common.returncode != 0:
        if "not a git repository" in common.stderr:
            print("dev-setup: not a git checkout; skipping the git hook install")
            return 0
        return _fail(f"git rev-parse failed:\n{common.stderr.strip()}")
    git_dir = run([git, "rev-parse", "--path-format=absolute", "--git-dir"])
    if git_dir.returncode != 0:
        return _fail(f"git rev-parse failed:\n{git_dir.stderr.strip()}")
    common_dir = Path(common.stdout.strip())
    hooks = common_dir / "hooks"

    hooks_path = run([git, "config", "--get", "core.hooksPath"])
    if hooks_path.returncode != 1:  # 1 means the key is unset; any other exit fails closed
        return _fail(
            f"core.hooksPath is set ({hooks_path.stdout.strip() or hooks_path.stderr.strip()}), "
            "so git ignores the hooks directory; unset it with "
            "`git config --unset-all core.hooksPath`"
        )
    problem = _hook_problem(hooks)
    if problem is not None:
        return _fail(problem)
    pre_commit = which("pre-commit")
    if pre_commit is None:
        return _fail("pre-commit not found on PATH; run `uv sync` first")

    result = run([pre_commit, "install", "--hook-type", "pre-commit"])
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        return result.returncode
    hooks.mkdir(parents=True, exist_ok=True)
    shim = hooks / "pre-push"
    if not shim.exists() or shim.read_text() != SHIM:
        shim.write_text(SHIM)
    shim.chmod(0o744)
    if Path(git_dir.stdout.strip()) != common_dir:
        print(
            "dev-setup: warning: this is a linked worktree; the hooks went to the shared "
            f"{hooks}. Commits there use this worktree's .venv, so re-run make dev-setup "
            "from the main checkout before removing this worktree."
        )
    print(f"dev-setup: commit hook and push gate installed in {hooks}")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m devtools.hooks")
    parser.add_argument("verb", choices=["install"])
    parser.parse_args(argv)
    return install()


if __name__ == "__main__":
    sys.exit(main())
